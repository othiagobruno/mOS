static void fe_be(u8 *o, const p256_fe *f) { for (int i = 0; i < 8; i++) { u32 w = f->v[7 - i]; o[4*i] = (u8)(w >> 24); o[4*i+1] = (u8)(w >> 16); o[4*i+2] = (u8)(w >> 8); o[4*i+3] = (u8)w; } }

int main(void) {
    sae_t s;
    memset(&s, 0, sizeof s);
    CHECK(sae_pwe_hnp(&s, A1, A2, "mekmitasdigoat"), "caçar e bicar acha o PWE");
    CHECK(sae_commit(&s, RAND, MASK), "commit");
    CHECK(!memcmp(s.scalar, LOCAL + 2, 32) && !memcmp(s.elem, LOCAL + 34, 64), "commit (escalar e elemento) = J.10");
    CHECK(sae_process_commit(&s, PEER + 2, PEER + 34), "commit do par aceito");
    CHECK(!memcmp(s.kck, KCK, 32), "KCK = J.10");
    CHECK(!memcmp(s.pmk, PMK, 32), "PMK = J.10");
    CHECK(!memcmp(s.pmkid, PMKID, 16), "PMKID = J.10");
    CHECK(!sae_process_commit(&s, s.scalar, s.elem), "commit refletido é recusado");
    u8 bad[64]; memcpy(bad, PEER + 34, 64); bad[63] ^= 1;
    CHECK(!sae_process_commit(&s, PEER + 2, bad), "elemento fora da curva é recusado");
    /* confirm: as duas pontas com os papéis trocados se aceitam */
    sae_t t; memset(&t, 0, sizeof t);
    CHECK(sae_pwe_hnp(&t, A2, A1, "mekmitasdigoat"), "o outro lado acha o mesmo PWE");
    sae_commit(&t, NULL, NULL);
    sae_t u; memset(&u, 0, sizeof u);
    sae_pwe_hnp(&u, A1, A2, "mekmitasdigoat");
    sae_commit(&u, NULL, NULL);
    bool ok = sae_process_commit(&u, t.scalar, t.elem) && sae_process_commit(&t, u.scalar, u.elem);
    u8 cu[32], ct[32];
    u16 su = sae_confirm(&u, cu), st = sae_confirm(&t, ct);
    CHECK(ok && !memcmp(u.pmk, t.pmk, 32) && sae_check_confirm(&t, su, cu) && sae_check_confirm(&u, st, ct), "duas pontas: mesmo PMK e confirms aceitos");
    cu[0] ^= 1;
    CHECK(!sae_check_confirm(&t, su, cu), "confirm adulterado é recusado");
    sae_t w; memset(&w, 0, sizeof w);
    sae_pwe_hnp(&w, A1, A2, "senha-errada");
    sae_commit(&w, NULL, NULL);
    sae_t x; memset(&x, 0, sizeof x);
    sae_pwe_hnp(&x, A2, A1, "mekmitasdigoat");
    sae_commit(&x, NULL, NULL);
    sae_process_commit(&w, x.scalar, x.elem); sae_process_commit(&x, w.scalar, w.elem);
    u8 cw[32]; u16 sw = sae_confirm(&w, cw);
    CHECK(!sae_check_confirm(&x, sw, cw), "senha diferente: o confirm não passa");
    /* H2E */
    u8 pt[64];
    CHECK(sae_derive_pt(pt, (const u8 *)"byteme", 6, "mekmitasdigoat", "psk4internet"), "H2E: PT");
    sae_t h; memset(&h, 0, sizeof h);
    CHECK(sae_pwe_h2e(&h, pt, B1, B2), "H2E: PWE = val·PT");
    u8 hx[32], hy[32]; fe_be(hx, &h.pwe_x); fe_be(hy, &h.pwe_y);
    CHECK(!memcmp(hx, PWE19X, 32) && !memcmp(hy, PWE19Y, 32), "H2E: PWE do grupo 19 = J.10");
    printf(fails ? "sae: %d FALHA(S)\n" : "sae: ok\n", fails);
    return fails != 0;
}
