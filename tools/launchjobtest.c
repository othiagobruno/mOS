static int nchildren(pnode_t *n) { int k = 0; for (pnode_t *c = n ? n->child : 0; c; c = c->next) k++; return k; }

static void policy_of(const char *txt, usize len, lj_policy_t *p, pnode_t **root) {
    *root = plist_parse(txt, len);
    memset(p, 0, sizeof *p);
    if (*root) lj_read_plist(*root, p);
}

static void test_restart_rules(void) {
    unsigned agent = LJ_KEEP_FAILURE | LJ_KEEP_CRASH;
    CHECK(!lj_keep_restart(agent, 0));           /* saiu com 0: o Setapp pediu para o agente parar */
    CHECK(lj_keep_restart(agent, 1));
    CHECK(lj_keep_restart(agent, 255));
    CHECK(lj_keep_restart(agent, -11));          /* SIGSEGV */
    CHECK(lj_keep_restart(agent, -6));           /* SIGABRT */
    CHECK(!lj_keep_restart(LJ_KEEP_CRASH, 1));
    CHECK(lj_keep_restart(LJ_KEEP_CRASH, -11));
    CHECK(lj_keep_restart(LJ_KEEP_SUCCESS, 0));
    CHECK(!lj_keep_restart(LJ_KEEP_SUCCESS, 3));
    CHECK(!lj_keep_restart(LJ_KEEP_SUCCESS, -9));
    CHECK(lj_keep_restart(LJ_KEEP_ALWAYS, 0) && lj_keep_restart(LJ_KEEP_ALWAYS, -9) && lj_keep_restart(LJ_KEEP_ALWAYS, 2));
    CHECK(!lj_keep_restart(0, -11) && !lj_keep_restart(0, 1));
    CHECK(lj_keep_runatload(LJ_KEEP_FAILURE | LJ_KEEP_CRASH));
    CHECK(!lj_keep_runatload(LJ_KEEP_CRASH));
    CHECK(lj_restart_delay_ms(1, 300) == 700);   /* ThrottleInterval conta do início */
    CHECK(lj_restart_delay_ms(1, 5000) == 0);
    CHECK(lj_restart_delay_ms(10, 0) == 10000);
    CHECK(lj_restart_delay_ms(0, 50000) == LJ_THROTTLE_DEFAULT_MS);
}

static void test_interval(void) {
    u64 next = 0;
    const unsigned iv = 21600;                   /* SetappUpdater: 6 h */
    CHECK(!lj_interval_tick(1000, &next, iv, 0));             /* arma, não dispara no load */
    CHECK(next == 1000 + 21600000ull);
    CHECK(!lj_interval_tick(next - 1, &next, iv, 0));
    u64 t = next;
    CHECK(lj_interval_tick(t, &next, iv, 0));
    CHECK(next == t + 21600000ull);
    t = next;
    CHECK(!lj_interval_tick(t + 5, &next, iv, 1));            /* ainda rodando: pula, rearma */
    CHECK(next == t + 5 + 21600000ull);
    u64 z = 0;
    CHECK(!lj_interval_tick(1, &z, 0, 0) && z == 0);          /* sem StartInterval */
}

